/**
 * google-service client — the STAFF Gmail mirrors, read for mail that reached a
 * staff mailbox instead of the sending mailbox it was written to.
 *
 * Why this service reads Gmail at all: a sending mailbox that forwarded every
 * message away without keeping a copy (`self-send/inbound-blindness.ts`) left
 * the prospects' replies in exactly one place, the staff Gmail the forward
 * pointed at, which google-service already mirrors. See
 * `self-send/forwarded-replies.ts`.
 *
 * FAILS LOUD: an unreadable mirror must never read as "nobody replied".
 */

const GOOGLE_SERVICE_URL = process.env.GOOGLE_SERVICE_URL;
const GOOGLE_SERVICE_API_KEY = process.env.GOOGLE_SERVICE_API_KEY;

/** One mirrored message, in the shape the recovery reads (whatever the wire calls it). */
export interface MirroredMessage {
  /** google-service's own id for the message (idempotent re-reads). */
  mirrorId: string;
  /** RFC 5322 Message-ID, angle brackets included when the sender put them. */
  messageId: string | null;
  inReplyTo: string | null;
  references: string | null;
  /** Lowercased header name -> value, for the automation markers the classifier reads. */
  headers: Record<string, string>;
  from: string | null;
  to: string[];
  cc: string[];
  subject: string | null;
  date: Date | null;
  text: string;
}

/** Who calls (logged by google-service) — a real identity, never a placeholder. */
export interface GoogleCallerIdentity {
  orgId: string;
  userId: string;
  runId: string;
}

function config(): { url: string; key: string } {
  if (!GOOGLE_SERVICE_URL || !GOOGLE_SERVICE_API_KEY) {
    throw new Error("GOOGLE_SERVICE_URL or GOOGLE_SERVICE_API_KEY is not set");
  }
  return { url: GOOGLE_SERVICE_URL, key: GOOGLE_SERVICE_API_KEY };
}

function identityHeaders(identity: GoogleCallerIdentity): Record<string, string> {
  return {
    "x-org-id": identity.orgId,
    "x-user-id": identity.userId,
    "x-run-id": identity.runId,
  };
}

/** One staff message to or from a person (google-service's staff conversation read). */
export interface StaffConversationMessage {
  mirrorId: string;
  direction: "inbound" | "outbound" | "other";
  from: string | null;
  to: string[];
  subject: string | null;
  date: Date | null;
  text: string;
}

/**
 * Every message between our STAFF (their own Gmail) and one person. An empty
 * list when staff never exchanged with them (google-service's 404 `no_messages`
 * or `no_staff_mailbox_connected` are both "nothing there", not failures).
 */
export async function fetchStaffConversation(
  email: string,
  identity: GoogleCallerIdentity,
): Promise<StaffConversationMessage[]> {
  const { url, key } = config();
  const response = await fetch(
    `${url}/internal/staff-mailboxes/conversation?email=${encodeURIComponent(email)}&limit=500`,
    { headers: { "x-api-key": key, ...identityHeaders(identity) } },
  );
  if (response.status === 404) return [];
  if (!response.ok) {
    throw new Error(
      `google-service GET /internal/staff-mailboxes/conversation failed: ${response.status} - ${(await response.text()).slice(0, 200)}`,
    );
  }
  const body = (await response.json()) as {
    threads?: Array<{
      messages?: Array<{
        gmailMessageId: string;
        direction: "inbound" | "outbound" | "other";
        fromEmail: string | null;
        to: string[] | null;
        subject: string | null;
        sentAt: string | null;
        bodyText: string | null;
        bodyTextOriginal: string | null;
      }>;
    }>;
  };
  return (body.threads ?? []).flatMap((t) =>
    (t.messages ?? []).map((m) => ({
      mirrorId: m.gmailMessageId,
      direction: m.direction,
      from: m.fromEmail,
      to: m.to ?? [],
      subject: m.subject,
      date: m.sentAt ? new Date(m.sentAt) : null,
      text: m.bodyTextOriginal ?? m.bodyText ?? "",
    })),
  );
}

/** One message as google-service's `addressed-messages` read serves it. */
interface AddressedMessageWire {
  id: string;
  messageId: string | null;
  inReplyTo: string | null;
  references: string[] | null;
  fromEmail: string | null;
  to: string[] | null;
  cc: string[] | null;
  subject: string | null;
  sentAt: string | null;
  automation: Record<string, string | null> | null;
  mimeType: string | null;
  bodyText: string | null;
}

/** google-service's automation field -> the header name the classifier reads. */
const AUTOMATION_HEADERS: Record<string, string> = {
  autoSubmitted: "auto-submitted",
  precedence: "precedence",
  xAutoreply: "x-autoreply",
  xAutorespond: "x-autorespond",
  xAutoResponseSuppress: "x-auto-response-suppress",
  xAutogenerated: "x-autogenerated",
  xFailedRecipients: "x-failed-recipients",
  listId: "list-id",
  listUnsubscribe: "list-unsubscribe",
  returnPath: "return-path",
  contentType: "content-type",
};

/** Pure: the wire message in the recovery's shape. */
export function toMirroredMessage(wire: AddressedMessageWire): MirroredMessage {
  const headers: Record<string, string> = {};
  for (const [field, header] of Object.entries(AUTOMATION_HEADERS)) {
    const value = wire.automation?.[field];
    if (typeof value === "string" && value.length > 0) headers[header] = value;
  }
  if (!headers["content-type"] && wire.mimeType) headers["content-type"] = wire.mimeType;
  return {
    mirrorId: wire.id,
    messageId: wire.messageId,
    inReplyTo: wire.inReplyTo,
    references: wire.references && wire.references.length > 0 ? wire.references.join(" ") : null,
    headers,
    from: wire.fromEmail,
    to: wire.to ?? [],
    cc: wire.cc ?? [],
    subject: wire.subject,
    date: wire.sentAt ? new Date(wire.sentAt) : null,
    text: wire.bodyText ?? "",
  };
}

/**
 * Every message in the staff mirrors sent TO or FROM any of `addresses`, paged
 * to the end (google-service `POST /internal/staff-mailboxes/addressed-messages`,
 * PRESSBEAT-RECOVER-1013). 404 `no_staff_mailbox_connected` = nothing mirrored.
 */
export async function fetchMirroredMailForAddresses(
  addresses: readonly string[],
  identity: GoogleCallerIdentity,
): Promise<MirroredMessage[]> {
  const { url, key } = config();
  const out: MirroredMessage[] = [];
  let cursor: string | null = null;
  for (;;) {
    const response: Response = await fetch(`${url}/internal/staff-mailboxes/addressed-messages`, {
      method: "POST",
      headers: { "Content-Type": "application/json", "x-api-key": key, ...identityHeaders(identity) },
      body: JSON.stringify({ addresses, limit: 500, ...(cursor ? { cursor } : {}) }),
    });
    if (response.status === 404) return out;
    if (!response.ok) {
      throw new Error(
        `google-service POST /internal/staff-mailboxes/addressed-messages failed: ${response.status} - ${(await response.text()).slice(0, 200)}`,
      );
    }
    const page = (await response.json()) as { messages?: AddressedMessageWire[]; nextCursor?: string | null };
    for (const wire of page.messages ?? []) out.push(toMirroredMessage(wire));
    cursor = page.nextCursor ?? null;
    if (!cursor) return out;
  }
}
